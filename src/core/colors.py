"""Code couleur de tous les messages Discord, salons et commandes : la couleur dit ce que le message annonce."""

INFO = 0x3B82F6   # bleu : information
OK = 0x22C55E     # vert : tout va bien, gain, réglage activé
WARN = 0xF59E0B   # orange : à surveiller
ALERT = 0xEF4444  # rouge : problème, perte
OFF = 0x6B7280    # gris : réglage coupé, annulé, rien à faire
